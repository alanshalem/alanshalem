using System.Text.RegularExpressions;

namespace Blog.Domain;

/// <summary>
/// An uploaded image, already optimized. Its files live in /media/{Hash}/{width}.{avif|webp}; the hash is the one of
/// the original file, so uploading the same image again reuses this asset instead of duplicating it.
/// </summary>
public sealed partial class MediaAsset
{
    /// <summary>Hexadecimal SHA-256.</summary>
    public const int HashLength = ContentHash.Length;

    public const int ColorLength = 7;

    /// <summary>The placeholder is embedded in the HTML of every page that shows the image: it has to be tiny.</summary>
    public const int MaxPlaceholderLength = 400;

    /// <summary>The main URL (for whoever does not build a srcset) is the widest WebP up to this size.</summary>
    public const int MaxDefaultWidth = 1600;

    public const string PlaceholderPrefix = "data:image/webp;base64,";

    // Constructor for EF Core.
    private MediaAsset()
    {
        Hash = Color = Placeholder = string.Empty;
    }

    public Guid Id { get; private set; }
    public string Hash { get; private set; }

    /// <summary>Size of the original already rotated by its EXIF (as seen, not as stored). For an animated GIF, of one frame.</summary>
    public int Width { get; private set; }

    public int Height { get; private set; }

    /// <summary>GIF or WebP with several frames: its variants keep the animation (see <see cref="MediaVariant.For"/>).</summary>
    public bool IsAnimated { get; private set; }

    /// <summary>Dominant color, #rrggbb: background while the image loads.</summary>
    public string Color { get; private set; }

    /// <summary>~16 px WebP as a data URI: instant blurry preview while the image loads.</summary>
    public string Placeholder { get; private set; }

    public DateTime CreatedAtUtc { get; private set; }

    public IReadOnlyList<MediaVariant> Variants => MediaVariant.For(Width, IsAnimated);

    public string Url => UrlOf(Variants.Last(variant => variant.Format == MediaFormat.Webp && variant.Width <= MaxDefaultWidth));

    // Generated by the server, never typed by a user: an invalid value is a programming error.
    [GeneratedRegex("^#[0-9a-f]{6}$")]
    private static partial Regex ColorPattern();

    public static MediaAsset Create(
        string hash, int width, int height, string color, string placeholder, DateTime nowUtc, bool animated = false)
    {
        ContentHash.EnsureValid(hash);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(width);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(height);

        if (!ColorPattern().IsMatch(color))
        {
            throw new ArgumentException("The color must have the #rrggbb format.", nameof(color));
        }

        if (!placeholder.StartsWith(PlaceholderPrefix, StringComparison.Ordinal) || placeholder.Length > MaxPlaceholderLength)
        {
            throw new ArgumentException($"The placeholder must be a WebP data URI of at most {MaxPlaceholderLength} characters.", nameof(placeholder));
        }

        return new MediaAsset
        {
            Id = Guid.CreateVersion7(),
            Hash = hash,
            Width = width,
            Height = height,
            IsAnimated = animated,
            Color = color,
            Placeholder = placeholder,
            CreatedAtUtc = nowUtc,
        };
    }

    /// <summary>Path of the file inside the media folder: {hash}/{width}.{extension}.</summary>
    public string RelativePathOf(MediaVariant variant) => $"{Hash}/{variant.Width}.{variant.Extension}";

    public string UrlOf(MediaVariant variant) => WebUrl.MediaPrefix + RelativePathOf(variant);
}
